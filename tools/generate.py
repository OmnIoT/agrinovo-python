#!/usr/bin/env python3
"""Writes everything that is derived from the sensor definitions.

The definitions live in the Agrinovo Arduino library, which is their single
source: dist/sensors.json (values, wiring, datasheet frames) and
sensors/<model>.json (the commands: address change, calibration, brush).

    src/agrinovo/sensors.py        one class per sensor
    docs/sensors/<model>.md        one page per sensor
    examples/sensors/<model>.py    one example per sensor
    README.md                      the supported-sensors table
    tests/definitions.json         the datasheet frames the tests replay

Usage: python tools/generate.py            write the files
       python tools/generate.py --check    fail if a file is out of date

The Arduino library is looked for next to this repository. Point somewhere
else with --source PATH or the AGRINOVO_ARDUINO environment variable.
"""

from __future__ import annotations

import argparse
import json
import keyword
import os
import re
import sys
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://agrinovo.io"
HEADER = "Generated by tools/generate.py from the Agrinovo sensor definitions. Do not edit by hand."

# Definition type -> number of registers it spans, and its description.
TYPES = {
    "u16": (1, "unsigned 16-bit"),
    "i16": (1, "signed 16-bit"),
    "sm16": (1, "16-bit, top bit is the sign"),
    "u16_dec": (2, "unsigned 16-bit, next register holds the decimal places"),
    "u32_abcd": (2, "unsigned 32-bit"),
    "u32_cdab": (2, "unsigned 32-bit, low word first"),
    "f32_abcd": (2, "float"),
    "f32_cdab": (2, "float, low word first"),
    "f32_dcba": (2, "float, least significant byte first"),
}

# Command argument type -> Python type and the range that fits the register.
ARG_TYPES = {
    "uint8_t": ("int", 0, 255),
    "uint16_t": ("int", 0, 65535),
    "int16_t": ("int", -32768, 32767),
    "float": ("float", -32768, 32767),
}

RESERVED = {"count", "index", "read", "units", "address", "bus"}


def fail(message: str) -> None:
    sys.exit("generate.py: " + message)


def num(value) -> int:
    return int(value, 16) if isinstance(value, str) else value


def hex2(value) -> str:
    return "0x%02X" % num(value)


def hex4(value) -> str:
    return "0x%04X" % num(value)


def snake(name: str) -> str:
    """electrodeSignal -> electrode_signal, co2Equivalent -> co2_equivalent."""
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()


def class_name(model: str) -> str:
    return re.sub(r"[^A-Za-z0-9]", "", model)


def slug(model: str) -> str:
    return model.lower()


def module_name(model: str) -> str:
    return slug(model).replace("-", "_")


def lower_first(text: str) -> str:
    """ "Dissolved oxygen" -> "dissolved oxygen"; "TDS" and "pH" stay."""
    return text[0].lower() + text[1:] if re.match(r"[A-Z][a-z]", text) else text


def listing(items) -> str:
    items = list(items)
    return items[0] if len(items) == 1 else "%s and %s" % (", ".join(items[:-1]), items[-1])


def crc16(frame) -> list:
    crc = 0xFFFF
    for byte in frame:
        crc ^= byte
        for _ in range(8):
            crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return [crc & 0xFF, crc >> 8]


def frame(text: str, append_crc: bool, where: str) -> str:
    """A frame from a definition, with its checksum added or checked."""
    data = [int(part, 16) for part in text.split()]
    if append_crc:
        data += crc16(data)
    elif crc16(data[:-2]) != data[-2:]:
        fail('%s: frame "%s" has a bad checksum' % (where, text))
    return " ".join("%02X" % byte for byte in data)


def float_text(value) -> str:
    return repr(float(value))


def product_url(s) -> str:
    return "%s/products/%s/" % (SITE, s["product"])


def datasheet_url(s) -> str:
    return "%s/datasheets/sensors/%s_Datasheet.pdf" % (SITE, s["datasheet"])


def object_name(s) -> str:
    """Probes go in the water; the rest are called sensors."""
    return "probe" if re.search("probe", s["name"], re.I) else "sensor"


# ------------------------------------------------------------------ loading


def load(source: Path) -> list:
    dist = source / "dist" / "sensors.json"
    if not dist.is_file():
        fail("no dist/sensors.json under %s. Pass --source or set AGRINOVO_ARDUINO." % source)
    sensors = json.loads(dist.read_text(encoding="utf-8"))
    files = sorted(p.name for p in (source / "sensors").glob("*.json"))
    if files != sorted(slug(s["model"]) + ".json" for s in sensors):
        fail("dist/sensors.json and sensors/*.json list different models; regenerate the Arduino library first")

    classes = set()
    for s in sensors:
        where = s["model"]
        raw = json.loads((source / "sensors" / (slug(s["model"]) + ".json")).read_text(encoding="utf-8"))
        s["cls"] = class_name(s["model"])
        if s["cls"] in classes or not s["cls"][0].isalpha():
            fail("%s: class name %s is taken or not valid" % (where, s["cls"]))
        classes.add(s["cls"])

        names = set()
        for v in s["values"]:
            v["name"] = snake(v["method"])
            if v["type"] not in TYPES:
                fail("%s: unknown type %s" % (where, v["type"]))
            if v["name"] in names or v["name"] in RESERVED or keyword.iskeyword(v["name"]):
                fail("%s: value name %s cannot be used in Python" % (where, v["name"]))
            names.add(v["name"])
        for f in s["frames"]:
            f["expect"] = {snake(key): value for key, value in f["expect"].items()}
            if set(f["expect"]) != names:
                fail("%s: a frame does not list exactly the sensor's values" % where)

        actions = raw.get("actions", [])
        if [a["doc"] for a in actions] != [a["description"] for a in s["actions"]]:
            fail("%s: the commands in dist/sensors.json and sensors/ differ" % where)
        s["commands"] = [command(a, names, where) for a in actions]
    return sensors


def command(a: dict, taken: set, where: str) -> dict:
    """One address, calibration or brush command, ready to write as a method."""
    where = "%s %s()" % (where, a["name"])
    c = {
        "name": snake(a["name"]),
        "read": bool(a.get("read")),
        "fn": a["fn"],
        "reg": num(a["reg"]),
        "sets_address": bool(a.get("setsAddress")),
        "low_byte_first": bool(a.get("lowByteFirst")),
        "arg": None,
        "value": None,
    }
    if c["name"] in taken or c["name"] in RESERVED or keyword.iskeyword(c["name"]):
        fail("%s: the name cannot be used in Python" % where)
    if c["fn"] not in ((3, 4) if c["read"] else (6, 16)):
        fail("%s: function %s does not fit" % (where, c["fn"]))

    # The descriptions are written for the Arduino methods, which report a
    # failure by their return value. Here a failure is raised.
    doc = a["doc"]
    if c["read"]:
        doc = doc.replace(", -1 no answer.", ".")
    if re.search(r"-1\b|\btrue\b|\bfalse\b|\bNAN\b|\(\)", doc):
        fail("%s: the description reads like C++: %s" % (where, doc))
    c["doc"] = doc

    vector = a["vector"]
    if not c["read"]:
        if ("arg" in a) == ("value" in a):
            fail("%s: needs either an argument or a fixed value" % where)
        if "value" in a:
            c["value"] = num(a["value"])
        else:
            kind = a["arg"]["type"]
            if kind not in ARG_TYPES:
                fail("%s: unknown argument type %s" % (where, kind))
            py, low, high = ARG_TYPES[kind]
            scale = a["arg"].get("scale", 0)
            if bool(scale) != (kind == "float"):
                fail("%s: a float argument needs a scale, and only a float has one" % where)
            c["arg"] = {"name": snake(a["arg"]["name"]), "py": py, "low": low, "high": high, "scale": scale}
            if len(vector.get("args", [])) != 1:
                fail("%s: the example frame needs one argument" % where)
        if c["sets_address"] and not c["arg"]:
            fail("%s: an address change needs the new address" % where)

    c["vector"] = {
        "args": vector.get("args", []),
        "request": frame(vector["request"], vector.get("appendCrc", False), where),
    }
    if c["read"]:
        c["vector"]["response"] = frame(vector["response"], False, where)
        c["vector"]["expect"] = vector["expect"]
    return c


# ------------------------------------------------------------------ classes


def signature(c: dict, annotated: bool = True) -> str:
    arg = c["arg"]
    if not annotated:
        return "%s(%s)" % (c["name"], arg["name"] if arg else "")
    params = "self" + (", %s: %s" % (arg["name"], arg["py"]) if arg else "")
    return "%s(%s) -> %s" % (c["name"], params, "int" if c["read"] else "None")


def command_body(c: dict) -> str:
    reg, fn = hex4(c["reg"]), hex2(c["fn"])
    if c["read"]:
        return "return self.read_register(%s, %s)" % (reg, fn)
    if c["value"] is not None:
        value = c["value"]
        if c["low_byte_first"]:
            value = ((value & 0xFF) << 8) | (value >> 8)
        return "self.write_register(%s, %s, %s)" % (reg, hex4(value), fn)
    arg = c["arg"]
    value = '_raw("%s", %s, %d, %d%s)' % (
        arg["name"],
        arg["name"],
        arg["low"],
        arg["high"],
        ", %s" % float_text(arg["scale"]) if arg["scale"] else "",
    )
    if c["low_byte_first"]:
        value = "_low_byte_first(%s)" % value  # this sensor expects the low byte first
    if c["sets_address"]:
        return "self._write_address(%s, %s, %s, %s)" % (reg, value, fn, arg["name"])
    return "self.write_register(%s, %s, %s)" % (reg, value, fn)


def docstring(text: str, indent: str) -> str:
    lines = textwrap.wrap(text, 88 - len(indent))
    if len(lines) == 1 and len(lines[0]) + len(indent) + 6 <= 88:
        return '%s"""%s"""' % (indent, lines[0])
    return '%s"""%s\n%s"""' % (indent, ("\n" + indent).join(lines), indent)


def class_source(s: dict) -> str:
    cls = s["cls"]
    reading = "\n".join("    %s: float  #: %s" % (v["name"], v["unit"]) for v in s["values"])
    fields = "\n".join(
        '        Field("%s", %d, "%s", %s, "%s", "%s", %d),'
        % (v["name"], v["offset"], v["type"], float_text(v["scale"]), v["unit"], v["label"], v["decimals"])
        for v in s["values"]
    )
    methods = "".join(
        "\n    def %s:\n%s\n        %s\n" % (signature(c), docstring(c["doc"], "        "), command_body(c))
        for c in s["commands"]
    )
    what = listing(lower_first(v["label"]) for v in s["values"])
    return '''class {cls}Reading(NamedTuple):
    """What {cls}.read() returns."""

{reading}


class {cls}(Sensor):
    """{model}: {name}.

    {url}
    """

    MODEL = "{model}"
    NAME = "{name}"
    DEFAULT_ADDRESS = {address}
    BAUDRATE = {baud}
    FUNCTION = {fn}
    START = {start}
    COUNT = {count}
    FIELDS = (
{fields}
    )
    Reading = {cls}Reading

    def read(self) -> {cls}Reading:
{read_doc}
        return super().read()
{methods}'''.format(
        cls=cls,
        reading=reading,
        model=s["model"],
        name=s["name"],
        url=product_url(s),
        address=s["address"],
        baud=s["baud"],
        fn=hex2(s["read"]["function"]),
        start=hex4(s["read"]["start"]),
        count=s["read"]["count"],
        fields=fields,
        read_doc=docstring("Reads %s." % what, "        "),
        methods=methods,
    )


def sensors_module(sensors: list) -> str:
    exports = "\n".join('    "%s",' % s["cls"] for s in sensors)
    table = "\n".join('    "%s": %s,' % (s["model"], s["cls"]) for s in sensors)
    return '''"""One class per Agrinovo sensor.

{header}
"""

from __future__ import annotations

from typing import Dict, NamedTuple, Type

from .sensor import Field, Sensor, _low_byte_first, _raw

__all__ = [
{exports}
]


{classes}

#: Every sensor class, by model name.
SENSORS: Dict[str, Type[Sensor]] = {{
{table}
}}
'''.format(
        header=HEADER,
        exports=exports,
        classes="\n\n".join(class_source(s) for s in sensors),
        table=table,
    )


# ----------------------------------------------------------------- examples


def wiring_lines(s: dict) -> str:
    width = max(len(color) for color, _ in s["wiring"])
    lines = []
    for color, role in s["wiring"]:
        text = role
        if role == "Supply +":
            text = "supply +, %s" % s["supply"]
        if role == "Supply ground":
            text = "supply ground"
        lines.append("  %s  %s" % (color.ljust(width), text))
    return "\n".join(lines)


def example(s: dict) -> str:
    obj = object_name(s)
    prints = "\n".join(
        '            print(f"%s: {reading.%s:.%df} %s")' % (v["label"], v["name"], v["decimals"], v["unit"])
        for v in s["values"]
    )
    return '''"""Agrinovo {model} {name}.

Prints {what} every 5 seconds.

{cable}
{wiring}

The computer talks to the sensor through a USB to RS485 adapter: A to A,
B to B. Run this file with the adapter's port, for example:

    python {module}.py /dev/ttyUSB0

{url}
"""

import sys
import time

import agrinovo

PORT = sys.argv[1] if len(sys.argv) > 1 else "/dev/ttyUSB0"

with agrinovo.Bus(PORT, baudrate={baud}) as bus:
    {obj} = agrinovo.{cls}(bus)  # Modbus address {address}
    while True:
        try:
            reading = {obj}.read()
{prints}
        except agrinovo.AgrinovoError as error:
            print(error)
        time.sleep(5)
'''.format(
        model=s["model"],
        name=lower_first(s["name"]),
        what=listing(lower_first(v["label"]) for v in s["values"]),
        cable="Sensor terminals" if s["wiringKind"] == "Terminal" else "Sensor cable",
        wiring=wiring_lines(s),
        module=module_name(s["model"]),
        url=product_url(s),
        baud=s["baud"],
        obj=obj,
        cls=s["cls"],
        address=s["address"],
        prints=prints,
    )


# --------------------------------------------------------------------- docs


def doc(s: dict) -> str:
    start = s["read"]["start"]
    values = "\n".join(
        "| `%s` | %s | %s | %s | %s%s |"
        % (
            v["name"],
            v["label"],
            v["unit"],
            hex4(start + v["offset"]),
            TYPES[v["type"]][1],
            ", x %s" % v["scale"] if v["scale"] != 1 else "",
        )
        for v in s["values"]
    )
    wiring = "\n".join(
        "| %s | %s |" % (color, "%s (%s)" % (role, s["supply"]) if role == "Supply +" else role)
        for color, role in s["wiring"]
    )
    commands = ""
    if s["commands"]:
        rows = "\n".join("| `%s` | %s |" % (signature(c, False), c["doc"]) for c in s["commands"])
        commands = (
            "\n## Settings and calibration\n\n| Method | What it does |\n|:--|:--|\n%s\n\n"
            "A method returns once the sensor has confirmed the command and raises "
            "`agrinovo.AgrinovoError` when it has not.\n" % rows
        )
    count = s["read"]["count"]
    return """# {model}: {name}

Class `agrinovo.{cls}`. [Product page]({product}) · [Datasheet]({datasheet})

## Wiring

| {kind} | Connect to |
|:--|:--|
{wiring}

A and B go to the A and B terminals of the RS485 adapter. When the adapter has a ground terminal, join it to the supply ground.

## Values

`read()` returns these, by name:

| Name | Value | Unit | Register | Stored as |
|:--|:--|:--|:--|:--|
{values}

The sensor is read with function {fn}, {count} register{plural} from {start}, at {baud} baud 8N1. Factory address: {address}.
{note}{commands}
## Example

```python
{example}```
""".format(
        model=s["model"],
        name=s["name"],
        cls=s["cls"],
        product=product_url(s),
        datasheet=datasheet_url(s),
        kind=s["wiringKind"],
        wiring=wiring,
        values=values,
        fn=hex2(s["read"]["function"]),
        count=count,
        plural="s" if count > 1 else "",
        start=hex4(start),
        baud=s["baud"],
        address=s["address"],
        note="\n%s\n" % s["note"] if s["note"] else "",
        commands=commands,
        example=example(s),
    )


def readme(sensors: list) -> str:
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    start, end = "<!-- sensors:start -->", "<!-- sensors:end -->"
    if start not in text or end not in text:
        fail("README.md has lost its sensors markers")
    rows = "\n".join(
        "| [%s](docs/sensors/%s.md) | %s | `%s` | %s |"
        % (
            s["model"],
            slug(s["model"]),
            s["name"],
            s["cls"],
            ", ".join(lower_first(v["label"]) for v in s["values"]),
        )
        for s in sensors
    )
    table = "| Model | Sensor | Class | Values |\n|:--|:--|:--|:--|\n" + rows
    return "%s\n%s\n%s" % (text[: text.index(start) + len(start)], table, text[text.index(end) :])


def test_data(sensors: list) -> str:
    """The frames and command examples the tests replay, checksums included."""
    data = [
        {
            "model": s["model"],
            "class": s["cls"],
            "address": s["address"],
            "values": [v["name"] for v in s["values"]],
            "frames": [
                {key: f[key] for key in ("request", "response", "expect", "tolerance")} for f in s["frames"]
            ],
            "commands": [
                {
                    "method": c["name"],
                    "read": c["read"],
                    "sets_address": c["sets_address"],
                    **c["vector"],
                }
                for c in s["commands"]
            ],
        }
        for s in sensors
    ]
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


# -------------------------------------------------------------------- write


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if a generated file is out of date")
    parser.add_argument("--source", help="path of the Agrinovo Arduino library")
    args = parser.parse_args()
    source = Path(args.source or os.environ.get("AGRINOVO_ARDUINO") or ROOT.parent / "agrinovo-arduino")

    sensors = load(source.expanduser())
    files = {
        "src/agrinovo/sensors.py": sensors_module(sensors),
        "README.md": readme(sensors),
        "tests/definitions.json": test_data(sensors),
    }
    for s in sensors:
        files["examples/sensors/%s.py" % module_name(s["model"])] = example(s)
        files["docs/sensors/%s.md" % slug(s["model"])] = doc(s)

    # A model that has left the definitions must not leave its files behind.
    for folder, suffix in (("examples/sensors", ".py"), ("docs/sensors", ".md")):
        for path in sorted((ROOT / folder).glob("*" + suffix)):
            rel = "%s/%s" % (folder, path.name)
            if rel not in files:
                files[rel] = None

    stale = 0
    for rel, content in files.items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8") if path.is_file() else None
        if current == content:
            continue
        stale += 1
        if args.check:
            print("out of date: %s" % rel, file=sys.stderr)
        elif content is None:
            path.unlink()
            print("removed %s" % rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
            print("wrote %s" % rel)
    if args.check and stale:
        sys.exit("\nRun: python tools/generate.py")
    if args.check:
        print("All %d generated files are up to date." % len(files))
    else:
        print("%d sensors, %d file(s) written." % (len(sensors), stale))


if __name__ == "__main__":
    main()
